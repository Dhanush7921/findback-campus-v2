interface I18n { lang: Lang; setLang: (l: Lang) => void; t: (k: Key) => string }
const Ctx = createContext<I18n>({ lang: 'en', setLang: () => {}, t: (k) => en[k] });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try { return (localStorage.getItem('fb.lang') as Lang) === 'te' ? 'te' : 'en'; } catch { return 'en'; }
  });
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem('fb.lang', l); } catch { /* ignore */ }
  }, []);
  const value = useMemo<I18n>(() => ({ lang, setLang, t: (k) => (lang === 'te' ? te[k] ?? en[k] : en[k]) }), [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
export type { Key as I18nKey };
